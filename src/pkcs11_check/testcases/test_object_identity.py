_UNIQUE_ID_VERSION_FLOOR = (3, 0)
_HANDLE_SENTINEL = 0x51515151
_CALLER_UNIQUE_ID = b"caller-supplied-id"
# KEM staging refusals (mirrors test_kem's operation reject set): setup only,
# the judged UNIQUE_ID legs never route through this tuple.
_KEM_STAGING_REJECT_RVS = (
    CKR_DEVICE_ERROR,
    CKR_FUNCTION_FAILED,
    CKR_FUNCTION_NOT_SUPPORTED,
    CKR_GENERAL_ERROR,
    CKR_KEY_FUNCTION_NOT_PERMITTED,
    CKR_KEY_TYPE_INCONSISTENT,
    CKR_MECHANISM_INVALID,
    CKR_TEMPLATE_INCOMPLETE,
    CKR_TEMPLATE_INCONSISTENT,
)
_KIND_PRIORITY = {"metadata": 1, "lifecycle": 2, "policy": 2, "crypto": 3}
_SEVERITY_PRIORITY = {"INFO": 0, "LOW": 1, "MEDIUM": 2, "HIGH": 3, "CRITICAL": 4}


def _raise_strongest(records: list[C.Classification]) -> None:
    if not records:
        return
    strongest = max(
        records,
        key=lambda record: (
            1 if record.outcome == "fail" else 0,
            _SEVERITY_PRIORITY.get(record.severity, 0),
            _KIND_PRIORITY.get(record.kind or "", 0),
        ),
    )
    C.raise_for_record(strongest)


def _detail(*, producer_operation: str, **extra: Any) -> dict[str, Any]:
    detail: dict[str, Any] = {
        "attribute": {
            "name": ATTR_NAMES.get(int(CKA_UNIQUE_ID), "CKA_UNIQUE_ID"),
            "id": int(CKA_UNIQUE_ID),
        },
        "producer_operation": producer_operation,
    }
    detail.update(extra)
    return detail


def _require_unique_id_applicable(rs: Any) -> None:
    """Classify C_GetInfo and skip visibly below the v3.0 floor."""
    info = CK_INFO()
    rv = int(rs.raw.C_GetInfo(byref(info)))
    if rv != int(CKR_OK):
        if is_standard_ckr(rv) or is_vendor_defined_ckr(rv):
            C.xfail_as(
                "not_operational",
                kind="metadata",
                label="CKA_UNIQUE_ID version gate (C_GetInfo)",
                operation="C_GetInfo",
                inherit_mechanism=False,
                expected=CKR_OK,
                actual=rv,
                summary=f"C_GetInfo refused the UNIQUE_ID version gate: {ckr_name(rv)}",
            )
        C.fail_as(
            "self_contradiction",
            kind="metadata",
            label="CKA_UNIQUE_ID version gate (C_GetInfo)",
            operation="C_GetInfo",
            inherit_mechanism=False,
            expected=CKR_OK,
            actual=rv,
            summary=f"C_GetInfo returned undefined CK_RV {ckr_name(rv)}",
        )
    version = (int(info.cryptokiVersion.major), int(info.cryptokiVersion.minor))
    if version < _UNIQUE_ID_VERSION_FLOOR:
        pytest.skip(
            f"CKA_UNIQUE_ID requires PKCS#11 >= 3.0; cryptokiVersion is "
            f"{version[0]}.{version[1]} -- UNIQUE_ID not applicable"
        )


def _read_unique_id(
    rs: Any, handle: int, *, label: str, producer_operation: str
) -> tuple[bytes | None, list[C.Classification]]:
    """Read one UNIQUE_ID as opaque bytes; empty/malformed fails, missing xfails."""
    try:
        attrs = read_attributes(rs.raw, rs.sh, handle, [CKA_UNIQUE_ID])
    except CkrAssertionError as exc:
        reason = (
            "not_operational"
            if is_standard_ckr(exc.rv) or is_vendor_defined_ckr(exc.rv)
            else "self_contradiction"
        )
        return None, [
            C.record_as(
                reason,
                kind="metadata",
                label=label,
                operation="C_GetAttributeValue",
                inherit_mechanism=False,
                expected=CKR_OK,
                actual=exc.rv,
                detail=_detail(producer_operation=producer_operation),
                summary=f"{label}: CKA_UNIQUE_ID read returned {ckr_name(exc.rv)}",
            )
        ]
    # Missing UNIQUE_ID is an honest deviation and a refusal-with-data a
    # self-contradiction; attr_or_record records exactly those shapes
    # (with the observed CKR), so sniff its just-emitted records.
    before = len(C.get_records())
    value = attr_or_record(
        attrs,
        CKA_UNIQUE_ID,
        label=label,
        reason="honest_deviation",
        kind="metadata",
        inherit_mechanism=False,
    )
    if value is MISSING_ATTRIBUTE:
        added = C.get_records()[before:]
        for record in added:
            if record.detail is None:
                record.detail = {}
            record.detail.setdefault("producer_operation", producer_operation)
        return None, added
    if isinstance(value, str):
        raw = value.encode("utf-8")
    elif isinstance(value, bytes):
        raw = value
    else:
        return None, [
            C.record_as(
                "wrong_result",
                kind="metadata",
                label=label,
                operation="C_GetAttributeValue",
                inherit_mechanism=False,
                detail=_detail(producer_operation=producer_operation),
                summary=f"{label}: CKA_UNIQUE_ID has malformed type {type(value).__name__}",
            )
        ]
    if len(raw) == 0:
        return None, [
            C.record_as(
                "wrong_result",
                kind="metadata",
                label=label,
                operation="C_GetAttributeValue",
                inherit_mechanism=False,
                detail=_detail(producer_operation=producer_operation, id_len=0),
                summary=f"{label}: CKA_UNIQUE_ID is empty",
            )
        ]
    return raw, []


def _collect_ids(
    rs: Any, staged: list[tuple[int, str, str]], *, stable: bool = False
) -> list[C.Classification]:
    """Read every staged object's ID, then judge global distinctness."""
    records: list[C.Classification] = []
    ids: dict[bytes, int] = {}
    duplicates = 0
    for handle, leg_label, producer_operation in staged:
        value, read_records = _read_unique_id(
            rs, handle, label=leg_label, producer_operation=producer_operation
        )
        records.extend(read_records)
        if value is None:
            continue
        if stable:
            again, again_records = _read_unique_id(
                rs, handle, label=leg_label, producer_operation=producer_operation
            )
            records.extend(again_records)
            if again is not None and again != value:
                records.append(
                    C.record_as(
                        "wrong_result",
                        kind="metadata",
                        label=leg_label,
                        operation="C_GetAttributeValue",
                        inherit_mechanism=False,
                        detail=_detail(
                            producer_operation=producer_operation,
                            first_len=len(value),
                            second_len=len(again),
                        ),
                        summary=f"{leg_label}: CKA_UNIQUE_ID changed across rereads",
                    )
                )
        if value in ids:
            duplicates += 1
        else:
            ids[value] = handle
    if duplicates:
        records.append(
            C.record_as(
                "wrong_result",
                kind="metadata",
                label="CKA_UNIQUE_ID distinctness among live objects",
                operation="C_GetAttributeValue",
                inherit_mechanism=False,
                detail={
                    "attribute": {
                        "name": ATTR_NAMES.get(int(CKA_UNIQUE_ID), "CKA_UNIQUE_ID"),
                        "id": int(CKA_UNIQUE_ID),
                    },
                    "live_objects": len(staged),
                    "duplicate_reads": duplicates,
                },
                summary="CKA_UNIQUE_ID values are not distinct among live objects",
            )
        )
    return records


def _destroy_all(rs: Any, handles: list[int]) -> None:
    for handle in dict.fromkeys(handles):
        if handle:
            destroy_quietly(rs.raw, rs.sh, handle)


def _stage_created_objects(rs: Any) -> list[tuple[int, str, str]]:
    """Three C_CreateObject routes: data, imported AES, imported RSA public."""
    from cryptography.hazmat.primitives.asymmetric import rsa

    skip_unless_create_object_supported(rs)
    staged: list[tuple[int, str, str]] = []
    try:
        data = create_object(
            rs.raw,
            rs.sh,
            {
                CKA_CLASS: CKO_DATA,
                CKA_VALUE: b"qc7c-data",
                CKA_TOKEN: False,
                CKA_LABEL: "qc7c-created-data",
            },
        )
        staged.append((data, "CKA_UNIQUE_ID:created data object", "C_CreateObject"))
        secret = import_secret_key(
            rs.raw, rs.sh, CKK_AES, bytes(range(16)), attrs={CKA_LABEL: "qc7c-created-aes"}
        )
        staged.append((secret, "CKA_UNIQUE_ID:imported AES key", "C_CreateObject"))
        numbers = rsa.generate_private_key(65537, 2048).public_key().public_numbers()
        rsa_pub = create_object(
            rs.raw,
            rs.sh,
            {
                CKA_CLASS: CKO_PUBLIC_KEY,
                CKA_KEY_TYPE: CKK_RSA,
                CKA_MODULUS: numbers.n.to_bytes((numbers.n.bit_length() + 7) // 8, "big"),
                CKA_PUBLIC_EXPONENT: numbers.e.to_bytes((numbers.e.bit_length() + 7) // 8, "big"),
                CKA_TOKEN: False,
                CKA_VERIFY: True,
                CKA_LABEL: "qc7c-created-rsa",
            },
        )
        staged.append((rsa_pub, "CKA_UNIQUE_ID:imported RSA public key", "C_CreateObject"))
    except BaseException:
        _destroy_all(rs, [h for h, _, _ in staged])
        raise
    return staged


def _stage_generated_objects(rs: Any) -> list[tuple[int, str, str]]:
    staged: list[tuple[int, str, str]] = []
    try:
        first = gen_aes_key_or_xfail(
            rs, bits=128, attrs={CKA_LABEL: "qc7c-gen-aes-1"}, purpose="QC7c generated IDs"
        )
        staged.append((first, "CKA_UNIQUE_ID:generated AES key 1", "C_GenerateKey"))
        second = gen_aes_key_or_xfail(
            rs, bits=128, attrs={CKA_LABEL: "qc7c-gen-aes-2"}, purpose="QC7c generated IDs"
        )
        staged.append((second, "CKA_UNIQUE_ID:generated AES key 2", "C_GenerateKey"))
        pub, priv = gen_rsa_keypair_or_xfail(rs, 2048)
        staged.append((pub, "CKA_UNIQUE_ID:generated RSA public half", "C_GenerateKeyPair"))
        staged.append((priv, "CKA_UNIQUE_ID:generated RSA private half", "C_GenerateKeyPair"))
    except BaseException:
        _destroy_all(rs, [h for h, _, _ in staged])
        raise
    return staged


class TestUniqueIdGeneration:
    """QC7c: every creator mints a nonempty, distinct, stable UNIQUE_ID."""

    def test_created_objects_have_distinct_unique_ids(self, p11_raw_session: Any) -> None:
        """Three C_CreateObject routes hold distinct stable IDs simultaneously."""
        rs = p11_raw_session
        _require_unique_id_applicable(rs)
        staged = _stage_created_objects(rs)
        try:
            _raise_strongest(_collect_ids(rs, staged, stable=True))
        finally:
            _destroy_all(rs, [h for h, _, _ in staged])

    def test_generated_objects_have_distinct_unique_ids(self, p11_raw_session: Any) -> None:
        """GenerateKey and both GenerateKeyPair halves hold distinct IDs."""
        rs = p11_raw_session
        _require_unique_id_applicable(rs)
        staged = _stage_generated_objects(rs)
        try:
            _raise_strongest(_collect_ids(rs, staged, stable=True))
        finally:
            _destroy_all(rs, [h for h, _, _ in staged])

    def test_copy_gets_own_unique_id(self, p11_raw_session: Any) -> None:
        """A copy gets its own ID and the source ID is unchanged."""
        rs = p11_raw_session
        _require_unique_id_applicable(rs)
        source = gen_aes_key_or_xfail(
            rs, bits=128, attrs={CKA_LABEL: "qc7c-copy-source"}, purpose="QC7c copy ID"
        )
        copied = 0
        try:
            try:
                copied = copy_object(rs.raw, rs.sh, source)
            except AssertionError as exc:
                xfail_if_known_ckr(
                    exc, KEYPAIR_RUNTIME_REJECT_RVS, "QC7c copy setup is not operational"
                )
                raise
            records: list[C.Classification] = []
            source_id, source_records = _read_unique_id(
                rs,
                source,
                label="CKA_UNIQUE_ID:copy source",
                producer_operation="C_GenerateKey",
            )
            records.extend(source_records)
            copy_id, copy_records = _read_unique_id(
                rs,
                copied,
                label="CKA_UNIQUE_ID:copied object",
                producer_operation="C_CopyObject",
            )
            records.extend(copy_records)
            reread_id, reread_records = _read_unique_id(
                rs,
                source,
                label="CKA_UNIQUE_ID:copy source reread",
                producer_operation="C_GenerateKey",
            )
            records.extend(reread_records)
            if source_id is not None and copy_id is not None and copy_id == source_id:
                records.append(
                    C.record_as(
                        "wrong_result",
                        kind="metadata",
                        label="CKA_UNIQUE_ID:copied object",
                        operation="C_GetAttributeValue",
                        inherit_mechanism=False,
                        detail=_detail(producer_operation="C_CopyObject", id_len=len(copy_id)),
                        summary="copy retained the source CKA_UNIQUE_ID",
                    )
                )
            if source_id is not None and reread_id is not None and reread_id != source_id:
                records.append(
                    C.record_as(
                        "wrong_result",
                        kind="metadata",
                        label="CKA_UNIQUE_ID:copy source reread",
                        operation="C_GetAttributeValue",
                        inherit_mechanism=False,
                        detail=_detail(
                            producer_operation="C_GenerateKey",
                            first_len=len(source_id),
                            second_len=len(reread_id),
                        ),
                        summary="source CKA_UNIQUE_ID changed after copy",
                    )
                )
            _raise_strongest(records)
        finally:
            if copied:
                destroy_quietly(rs.raw, rs.sh, copied)
            destroy_quietly(rs.raw, rs.sh, source)

    def test_unique_ids_distinct_across_creators(self, p11_raw_session: Any) -> None:
        """Create+Generate+Pair+Copy objects are globally distinct while live."""
        rs = p11_raw_session
        _require_unique_id_applicable(rs)
        staged = _stage_created_objects(rs)
        try:
            staged.extend(_stage_generated_objects(rs))
            source = staged[0][0]
            try:
                copied = copy_object(rs.raw, rs.sh, source)
            except AssertionError as exc:
                xfail_if_known_ckr(
                    exc, KEYPAIR_RUNTIME_REJECT_RVS, "QC7c copy setup is not operational"
                )
                raise
            staged.append((copied, "CKA_UNIQUE_ID:copied object", "C_CopyObject"))
            _raise_strongest(_collect_ids(rs, staged))
        finally:
            _destroy_all(rs, [h for h, _, _ in staged])

    def test_kem_outputs_have_unique_ids(self, p11_raw_session: Any) -> None:
        """ML-KEM pair halves and encap/decap secrets hold distinct IDs."""
        rs = p11_raw_session
        _require_unique_id_applicable(rs)
        if not rs.has_mechanism("ML_KEM_KEY_PAIR_GEN"):
            pytest.skip("ML_KEM_KEY_PAIR_GEN not supported by module")
        if not rs.has_mechanism("ML_KEM"):
            pytest.skip("ML_KEM not supported by module")
        try:
            pub, priv = gen_keypair(
                rs.raw,
                rs.sh,
                int(CKM_ML_KEM_KEY_PAIR_GEN),
                pub_base=[attr_ulong(CKA_PARAMETER_SET, int(CKP_ML_KEM_512))],
                priv_base=[],
                public_attrs={CKA_TOKEN: False, CKA_ENCAPSULATE: True},
                private_attrs={CKA_TOKEN: False, CKA_DECAPSULATE: True},
                pub_skip={CKA_PARAMETER_SET},
            )
        except AssertionError as exc:
            xfail_if_known_ckr(
                exc, KEYPAIR_RUNTIME_REJECT_RVS, "QC7c ML-KEM pair setup is not operational"
            )
            raise
        staged: list[tuple[int, str, str]] = [
            (pub, "CKA_UNIQUE_ID:ML-KEM public half", "C_GenerateKeyPair"),
            (priv, "CKA_UNIQUE_ID:ML-KEM private half", "C_GenerateKeyPair"),
        ]
        secret_attrs: dict[Any, Any] = {
            CKA_CLASS: CKO_SECRET_KEY,
            CKA_KEY_TYPE: CKK_AES,
            CKA_VALUE_LEN: 32,
            CKA_TOKEN: False,
            CKA_SENSITIVE: False,
            CKA_EXTRACTABLE: True,
        }
        try:
            try:
                encapsulated, ciphertext = encapsulate_key(
                    rs.raw, rs.sh, pub, CKM_ML_KEM, attrs=secret_attrs
                )
            except AssertionError as exc:
                xfail_if_known_ckr(
                    exc, _KEM_STAGING_REJECT_RVS, "QC7c ML-KEM encapsulate is not operational"
                )
                raise
            staged.append((encapsulated, "CKA_UNIQUE_ID:encapsulated secret", "C_EncapsulateKey"))
            try:
                decapsulated = decapsulate_key(
                    rs.raw, rs.sh, priv, CKM_ML_KEM, ciphertext, attrs=secret_attrs
                )
            except AssertionError as exc:
                xfail_if_known_ckr(
                    exc, _KEM_STAGING_REJECT_RVS, "QC7c ML-KEM decapsulate is not operational"
                )
                raise
            staged.append((decapsulated, "CKA_UNIQUE_ID:decapsulated secret", "C_DecapsulateKey"))
            _raise_strongest(_collect_ids(rs, staged))
        finally:
            _destroy_all(rs, [h for h, _, _ in staged])


def _inventory(rs: Any) -> list[int]:
    """All currently visible object handles (exhaustive unfiltered search)."""
    return find_objects_exhaustive(rs.raw, rs.sh)


def _handle_class(
    handle_value: int,
    *,
    found: list[int],
    new_handles: list[int],
    before: list[int] | None = None,
) -> str:
    if handle_value == _HANDLE_SENTINEL:
        return "sentinel"
    if handle_value == 0:
        return "zero"
    if before is not None and handle_value in before:
        return "pre-existing"
    if handle_value in found or handle_value in new_handles:
        return "new-live"
    return "dead-nonzero"


def _judge_override(
    rs: Any,
    *,
    rv: int,
    handle_value: int,
    label: str,
    producer_operation: str,
    label_text: str | None,
    leaked: list[int],
    inventory_before: list[int],
    attempt_attrs: dict[Any, Any] | None = None,
    identities: tuple[tuple[int, int], ...] = (),
) -> list[C.Classification]:
    """Two-tier override oracle shared by Create/Generate/Copy legs.

    Refusal legs judge objects, not output-buffer writes (adjudicated O1):
    the spec defines no handle state on a failed creator, so only a
    proved-new leftover object FAILs; an unproved inventory delta is an
    honest deviation and is left alive. A dead nonzero handle write is an
    honest deviation; zero and the untouched sentinel are normalized.
    """
    records: list[C.Classification] = []
    found: list[int] = []
    if label_text is not None:
        found = find_objects_exhaustive(
            rs.raw, rs.sh, template(attr_bytes(CKA_LABEL, label_text.encode()))
        )
    before_set = set(inventory_before)
    inventory_after = _inventory(rs)
    new_handles = sorted(set(inventory_after) - before_set)
    proved_new, unproved_new = partition_proved_new(
        rs.raw,
        rs.sh,
        inventory_before,
        inventory_after,
        attempt_templates=(attempt_attrs,) if attempt_attrs is not None else (),
        identities=identities,
        error_handles=(handle_value,),
    )
    proved_set = set(proved_new)
    found_new = [handle for handle in found if handle in proved_set]
    judge_detail: dict[str, Any] = {
        "handle_after": handle_value,
        "handle_class": _handle_class(
            handle_value, found=found_new, new_handles=proved_new, before=inventory_before
        ),
        "found_by_label": list(found),
        "new_handles": new_handles,
        "proved_new_handles": proved_new,
        "unproved_new_handles": unproved_new,
    }
    if rv == int(CKR_OK):
        # A success output handle is not ownership proof (R2): only a
        # proved-new handle (inventory delta, or a baseline-filtered
        # label hit) may be read or destroyed. A returned handle that
        # already existed proves the creator created nothing for this
        # attempt; it is evidence only and is never touched.
        leaked.extend(h for h in proved_new if h not in leaked)
        if handle_value in before_set:
            records.append(
                C.record_as(
                    "self_contradiction",
                    kind="metadata",
                    label=label,
                    operation=producer_operation,
                    inherit_mechanism=False,
                    actual=rv,
                    detail=_detail(
                        producer_operation=producer_operation,
                        outcome="pre-existing-handle",
                        **judge_detail,
                    ),
                    summary=(
                        f"{label}: CKR_OK returned pre-existing object "
                        f"{handle_value} instead of a newly created object"
                    ),
                )
            )
            if not proved_new:
                return records
        created = handle_value
        target = 0
        if created != _HANDLE_SENTINEL and created in proved_set:
            target = created
        elif found_new:
            target = found_new[0]
        elif proved_new:
            target = proved_new[0]
        stored: bytes | None = None
        if target:
            stored, stored_records = _read_unique_id(
                rs, target, label=label, producer_operation=producer_operation
            )
            records.extend(stored_records)
        if stored is not None and stored == _CALLER_UNIQUE_ID:
            records.append(
                C.record_as(
                    "accepted_invalid",
                    kind="metadata",
                    label=label,
                    operation=producer_operation,
                    inherit_mechanism=False,
                    expected=CKR_ATTRIBUTE_READ_ONLY,
                    actual=rv,
                    detail=_detail(
                        producer_operation=producer_operation, outcome="honored", **judge_detail
                    ),
                    summary=f"{label}: caller-supplied CKA_UNIQUE_ID was honored",
                )
            )
        else:
            records.append(
                C.record_as(
                    "honest_deviation",
                    kind="metadata",
                    label=label,
                    operation=producer_operation,
                    inherit_mechanism=False,
                    expected=CKR_ATTRIBUTE_READ_ONLY,
                    actual=rv,
                    detail=_detail(
                        producer_operation=producer_operation, outcome="ignored", **judge_detail
                    ),
                    summary=(
                        f"{label}: caller-supplied CKA_UNIQUE_ID was accepted but "
                        "ignored (stored ID differs); refusal is required"
                    ),
                )
            )
        return records
    if proved_new:
        # A refused creator left a proved-new object behind. Only those
        # correlated handles are destroyed by the caller; a bare
        # handle_value and any unproved delta are never touched.
        leaked.extend(h for h in proved_new if h not in leaked)
        records.append(
            C.record_as(
                "self_contradiction",
                kind="metadata",
                label=label,
                operation=producer_operation,
                inherit_mechanism=False,
                actual=rv,
                detail=_detail(producer_operation=producer_operation, **judge_detail),
                summary=f"{label}: refusal {ckr_name(rv)} left an object behind",
            )
        )
    elif unproved_new and (
        rv == int(CKR_ATTRIBUTE_READ_ONLY) or is_standard_ckr(rv) or is_vendor_defined_ckr(rv)
    ):
        records.append(
            C.record_as(
                "honest_deviation",
                kind="metadata",
                label=label,
                operation=producer_operation,
                inherit_mechanism=False,
                actual=rv,
                detail=_detail(
                    producer_operation=producer_operation,
                    disposition="unproved-effect",
                    **judge_detail,
                ),
                summary=(
                    f"{label}: refusal {ckr_name(rv)} with an unproved "
                    "inventory delta; zero-delta unproved"
                ),
            )
        )
    elif handle_value not in (_HANDLE_SENTINEL, 0):
        records.append(
            C.record_as(
                "honest_deviation",
                kind="metadata",
                label=label,
                operation=producer_operation,
                inherit_mechanism=False,
                actual=rv,
                detail=_detail(producer_operation=producer_operation, **judge_detail),
                summary=(
                    f"{label}: refusal {ckr_name(rv)} wrote non-invalid output "
                    f"handle {handle_value}; no object created"
                ),
            )
        )
    elif rv == int(CKR_ATTRIBUTE_READ_ONLY):
        pass  # Canonical: refused, no object (sentinel or zero write).
    elif is_standard_ckr(rv) or is_vendor_defined_ckr(rv):
        records.append(
            C.record_as(
                "nonspec_reject",
                kind="metadata",
                label=label,
                operation=producer_operation,
                inherit_mechanism=False,
                expected=CKR_ATTRIBUTE_READ_ONLY,
                actual=rv,
                detail=_detail(producer_operation=producer_operation, **judge_detail),
                summary=f"{label}: rejected with {ckr_name(rv)}",
            )
        )
    else:
        records.append(
            C.record_as(
                "self_contradiction",
                kind="metadata",
                label=label,
                operation=producer_operation,
                inherit_mechanism=False,
                actual=rv,
                detail=_detail(producer_operation=producer_operation, **judge_detail),
                summary=f"{label}: rejected with undefined CK_RV {ckr_name(rv)}",
            )
        )
    return records


class TestUniqueIdOverride:
    """QC7c: caller-supplied CKA_UNIQUE_ID is forbidden on every creator."""

    def test_unique_id_override_rejected_on_create(self, p11_raw_session: Any) -> None:
        """Raw C_CreateObject with CKA_UNIQUE_ID: READ_ONLY, no object."""
        rs = p11_raw_session
        _require_unique_id_applicable(rs)
        skip_unless_create_object_supported(rs)
        label_text = "qc7c-override-create"
        attrs: dict[Any, Any] = {
            CKA_CLASS: CKO_DATA,
            CKA_VALUE: b"qc7c-override",
            CKA_TOKEN: False,
            CKA_LABEL: label_text,
            CKA_UNIQUE_ID: _CALLER_UNIQUE_ID,
        }
        tmpl = template(*pack_attrs(attrs))
        handle = CK_OBJECT_HANDLE(_HANDLE_SENTINEL)
        inventory_before = _inventory(rs)
        rv = int(rs.raw.C_CreateObject(rs.sh, tmpl.ptr, tmpl.count, byref(handle)))
        leaked: list[int] = []
        try:
            records = _judge_override(
                rs,
                rv=rv,
                handle_value=int(handle.value),
                label="CKA_UNIQUE_ID override on C_CreateObject",
                producer_operation="C_CreateObject",
                label_text=label_text,
                leaked=leaked,
                inventory_before=inventory_before,
                attempt_attrs=attrs,
            )
        finally:
            _destroy_all(rs, leaked)
        _raise_strongest(records)

    def test_unique_id_override_rejected_on_generate_and_copy(self, p11_raw_session: Any) -> None:
        """Raw C_GenerateKey and C_CopyObject override legs; both observed."""
        from pkcs11_check.raw.pack import mech_simple
        from pkcs11_check.raw.types_std import CKM_AES_KEY_GEN

        rs = p11_raw_session
        _require_unique_id_applicable(rs)
        records: list[C.Classification] = []
        leaked: list[int] = []
        source = 0
        try:
            gen_attrs: dict[Any, Any] = {
                CKA_KEY_TYPE: CKK_AES,
                CKA_VALUE_LEN: 16,
                CKA_TOKEN: False,
                CKA_LABEL: "qc7c-override-generate",
                CKA_UNIQUE_ID: _CALLER_UNIQUE_ID,
            }
            gen_tmpl = template(*pack_attrs(gen_attrs))
            gen_handle = CK_OBJECT_HANDLE(_HANDLE_SENTINEL)
            mech = mech_simple(int(CKM_AES_KEY_GEN))
            gen_inventory_before = _inventory(rs)
            gen_rv = int(
                rs.raw.C_GenerateKey(
                    rs.sh, mech.byref(), gen_tmpl.ptr, gen_tmpl.count, byref(gen_handle)
                )
            )
            records.extend(
                _judge_override(
                    rs,
                    rv=gen_rv,
                    handle_value=int(gen_handle.value),
                    label="CKA_UNIQUE_ID override on C_GenerateKey",
                    producer_operation="C_GenerateKey",
                    label_text="qc7c-override-generate",
                    leaked=leaked,
                    inventory_before=gen_inventory_before,
                    attempt_attrs=gen_attrs,
                    identities=((int(CKO_SECRET_KEY), int(CKK_AES)),),
                )
            )

            source = gen_aes_key_or_xfail(
                rs,
                bits=128,
                attrs={CKA_LABEL: "qc7c-override-copy-source"},
                purpose="QC7c copy-override source",
            )
            source_id, source_records = _read_unique_id(
                rs,
                source,
                label="CKA_UNIQUE_ID:copy-override source",
                producer_operation="C_GenerateKey",
            )
            records.extend(source_records)
            copy_attrs: dict[Any, Any] = {
                CKA_LABEL: "qc7c-override-copy",
                CKA_UNIQUE_ID: _CALLER_UNIQUE_ID,
            }
            copy_tmpl = template(*pack_attrs(copy_attrs))
            copy_handle = CK_OBJECT_HANDLE(_HANDLE_SENTINEL)
            copy_inventory_before = _inventory(rs)
            copy_rv = int(
                rs.raw.C_CopyObject(
                    rs.sh, source, copy_tmpl.ptr, copy_tmpl.count, byref(copy_handle)
                )
            )
            records.extend(
                _judge_override(
                    rs,
                    rv=copy_rv,
                    handle_value=int(copy_handle.value),
                    label="CKA_UNIQUE_ID override on C_CopyObject",
                    producer_operation="C_CopyObject",
                    label_text="qc7c-override-copy",
                    leaked=leaked,
                    inventory_before=copy_inventory_before,
                    attempt_attrs=copy_attrs,
                    identities=((int(CKO_SECRET_KEY), int(CKK_AES)),),
                )
            )
            reread_id, reread_records = _read_unique_id(
                rs,
                source,
                label="CKA_UNIQUE_ID:copy-override source reread",
                producer_operation="C_GenerateKey",
            )
            records.extend(reread_records)
            if source_id is not None and reread_id is not None and reread_id != source_id:
                records.append(
                    C.record_as(
                        "wrong_result",
                        kind="metadata",
                        label="CKA_UNIQUE_ID:copy-override source reread",
                        operation="C_GetAttributeValue",
                        inherit_mechanism=False,
                        detail=_detail(
                            producer_operation="C_GenerateKey",
                            first_len=len(source_id),
                            second_len=len(reread_id),
                        ),
                        summary="source CKA_UNIQUE_ID changed after override copy attempt",
                    )
                )
        finally:
            _destroy_all(rs, leaked)
            if source:
                destroy_quietly(rs.raw, rs.sh, source)
        _raise_strongest(records)
