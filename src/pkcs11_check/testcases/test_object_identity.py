def _raise_strongest(records: list[C.Classification]) -> None:
    if not records:
        return
    strongest = max(
        records,
        key=lambda record: (
            1 if record.outcome == "fail" else 0,
            _SEVERITY_PRIORITY.get(record.severity, 0),
            _KIND_PRIORITY.get(record.kind or "", 0),
        ),
    )
    C.raise_for_record(strongest)


def _detail(*, producer_operation: str, **extra: Any) -> dict[str, Any]:
    detail: dict[str, Any] = {
        "attribute": {
            "name": ATTR_NAMES.get(int(CKA_UNIQUE_ID), "CKA_UNIQUE_ID"),
            "id": int(CKA_UNIQUE_ID),
        },
        "producer_operation": producer_operation,
    }
    detail.update(extra)
    return detail


def _require_unique_id_applicable(rs: Any) -> None:
    """Classify C_GetInfo and skip visibly below the v3.0 floor."""
    info = CK_INFO()
    rv = int(rs.raw.C_GetInfo(byref(info)))
    if rv != int(CKR_OK):
        if is_standard_ckr(rv) or is_vendor_defined_ckr(rv):
            C.xfail_as(
                "not_operational",
                kind="metadata",
                label="CKA_UNIQUE_ID version gate (C_GetInfo)",
                operation="C_GetInfo",
                inherit_mechanism=False,
                expected=CKR_OK,
                actual=rv,
                summary=f"C_GetInfo refused the UNIQUE_ID version gate: {ckr_name(rv)}",
            )
        C.fail_as(
            "self_contradiction",
            kind="metadata",
            label="CKA_UNIQUE_ID version gate (C_GetInfo)",
            operation="C_GetInfo",
            inherit_mechanism=False,
            expected=CKR_OK,
            actual=rv,
            summary=f"C_GetInfo returned undefined CK_RV {ckr_name(rv)}",
        )
    version = (int(info.cryptokiVersion.major), int(info.cryptokiVersion.minor))
    if version < _UNIQUE_ID_VERSION_FLOOR:
        pytest.skip(
            f"CKA_UNIQUE_ID requires PKCS#11 >= 3.0; cryptokiVersion is "
            f"{version[0]}.{version[1]} -- UNIQUE_ID not applicable"
        )


def _read_unique_id(
    rs: Any, handle: int, *, label: str, producer_operation: str
) -> tuple[bytes | None, list[C.Classification]]:
    """Read one UNIQUE_ID as opaque bytes; empty/malformed fails, missing xfails."""
    try:
        attrs = read_attributes(rs.raw, rs.sh, handle, [CKA_UNIQUE_ID])
    except CkrAssertionError as exc:
        reason = (
            "not_operational"
            if is_standard_ckr(exc.rv) or is_vendor_defined_ckr(exc.rv)
            else "self_contradiction"
        )
        return None, [
            C.record_as(
                reason,
                kind="metadata",
                label=label,
                operation="C_GetAttributeValue",
                inherit_mechanism=False,
                expected=CKR_OK,
                actual=exc.rv,
                detail=_detail(producer_operation=producer_operation),
                summary=f"{label}: CKA_UNIQUE_ID read returned {ckr_name(exc.rv)}",
            )
        ]
    # Missing UNIQUE_ID is an honest deviation and a refusal-with-data a
    # self-contradiction; attr_or_record records exactly those shapes
    # (with the observed CKR), so sniff its just-emitted records.
    before = len(C.get_records())
    value = attr_or_record(
        attrs,
        CKA_UNIQUE_ID,
        label=label,
        reason="honest_deviation",
        kind="metadata",
        inherit_mechanism=False,
    )
    if value is MISSING_ATTRIBUTE:
        added = C.get_records()[before:]
        for record in added:
            if record.detail is None:
                record.detail = {}
            record.detail.setdefault("producer_operation", producer_operation)
        return None, added
    if isinstance(value, str):
        raw = value.encode("utf-8")
    elif isinstance(value, bytes):
        raw = value
    else:
        return None, [
            C.record_as(
                "wrong_result",
                kind="metadata",
                label=label,
                operation="C_GetAttributeValue",
                inherit_mechanism=False,
                detail=_detail(producer_operation=producer_operation),
                summary=f"{label}: CKA_UNIQUE_ID has malformed type {type(value).__name__}",
            )
        ]
    if len(raw) == 0:
        return None, [
            C.record_as(
                "wrong_result",
                kind="metadata",
                label=label,
                operation="C_GetAttributeValue",
                inherit_mechanism=False,
                detail=_detail(producer_operation=producer_operation, id_len=0),
                summary=f"{label}: CKA_UNIQUE_ID is empty",
            )
        ]
    return raw, []


def _collect_ids(
    rs: Any, staged: list[tuple[int, str, str]], *, stable: bool = False
) -> list[C.Classification]:
    """Read every staged object's ID, then judge global distinctness."""
    records: list[C.Classification] = []
    ids: dict[bytes, int] = {}
    duplicates = 0
    for handle, leg_label, producer_operation in staged:
        value, read_records = _read_unique_id(
            rs, handle, label=leg_label, producer_operation=producer_operation
        )
        records.extend(read_records)
        if value is None:
            continue
        if stable:
            again, again_records = _read_unique_id(
                rs, handle, label=leg_label, producer_operation=producer_operation
            )
            records.extend(again_records)
            if again is not None and again != value:
                records.append(
                    C.record_as(
                        "wrong_result",
                        kind="metadata",
                        label=leg_label,
                        operation="C_GetAttributeValue",
                        inherit_mechanism=False,
                        detail=_detail(
                            producer_operation=producer_operation,
                            first_len=len(value),
                            second_len=len(again),
                        ),
                        summary=f"{leg_label}: CKA_UNIQUE_ID changed across rereads",
                    )
                )
        if value in ids:
            duplicates += 1
        else:
            ids[value] = handle
    if duplicates:
        records.append(
            C.record_as(
                "wrong_result",
                kind="metadata",
                label="CKA_UNIQUE_ID distinctness among live objects",
                operation="C_GetAttributeValue",
                inherit_mechanism=False,
                detail={
                    "attribute": {
                        "name": ATTR_NAMES.get(int(CKA_UNIQUE_ID), "CKA_UNIQUE_ID"),
                        "id": int(CKA_UNIQUE_ID),
                    },
                    "live_objects": len(staged),
                    "duplicate_reads": duplicates,
                },
                summary="CKA_UNIQUE_ID values are not distinct among live objects",
            )
        )
    return records


def _destroy_all(rs: Any, handles: list[int]) -> None:
    for handle in dict.fromkeys(handles):
        if handle:
            destroy_quietly(rs.raw, rs.sh, handle)


def _baseline_or_void(rs: Any, *, label: str) -> list[int]:
    """Live-handle baseline for staging adoption (R3F2).

    A refused baseline voids staging visibly (honest-deviation
    unproved-effect: no output can be adopted without proving it is
    new); an undefined RV fails the metadata contract loud.
    """
    try:
        return _inventory(rs)
    except CkrAssertionError as exc:
        rv = exc.rv
        if not is_standard_ckr(rv) and not is_vendor_defined_ckr(rv):
            C.fail_as(
                "self_contradiction",
                kind="metadata",
                label=label,
                operation="C_FindObjects",
                inherit_mechanism=False,
                actual=rv,
                summary=(f"{label}: staging baseline returned undefined CK_RV {ckr_name(rv)}"),
            )
        C.xfail_as(
            "honest_deviation",
            kind="policy",
            label=label,
            operation="C_FindObjects",
            inherit_mechanism=False,
            actual=rv,
            summary=(f"{label}: staging baseline refused ({ckr_name(rv)}); adoption unproved"),
            detail={"disposition": "unproved-effect", "inventory_rv": ckr_name(rv)},
        )


def _adopt_staged(
    rs: Any,
    claimed: int,
    *,
    label: str,
    producer_operation: str,
    before: Collection[int],
    siblings: Collection[int],
    expect_label: str | bytes,
    expect_token: bool,
) -> int:
    """Adopt a staged output only with proved ownership (R3F2, R4-F1).

    A null handle, an already-staged sibling (alias), or a handle
    predating the baseline is a proved provider contradiction: fail
    WITHOUT staging it, or shared cleanup would destroy a foreign
    object (or the same object twice). A novel handle is adopted only
    with attempt correlation (label plus session-ness; staged fixtures
    never judge shape): a mismatch fails WITHOUT staging it, and an
    unreadable identity xfails unproved-effect WITHOUT staging it.
    Returns the adopted handle; never returns an unproved one.
    """
    if not claimed:
        cause = "a null handle"
    elif claimed in set(siblings):
        cause = "an already-staged handle (alias)"
    elif claimed in set(before):
        cause = "a pre-existing handle"
    else:
        try:
            adopt_correlated_output(
                rs,
                claimed,
                label=label,
                operation=producer_operation,
                expect_label=expect_label,
                expect_token=expect_token,
                expect_class=None,
                expect_key_type=None,
            )
        except OwnershipUnprovedError as exc:
            fields = ", ".join(f"{name}: {why}" for name, why in exc.fields.items())
            C.xfail_as(
                "honest_deviation",
                kind="policy",
                label=label,
                operation=producer_operation,
                inherit_mechanism=False,
                actual=int(CKR_OK),
                summary=(
                    f"{label}: {producer_operation} output ownership unproved "
                    f"({fields}); refusing to stage it"
                ),
                detail={"disposition": "unproved-effect", "handle": claimed},
            )
        return claimed
    C.fail_as(
        "self_contradiction",
        kind="policy",
        label=label,
        operation=producer_operation,
        inherit_mechanism=False,
        actual=int(CKR_OK),
        summary=(
            f"{label}: {producer_operation} returned {cause} ({claimed}); refusing to stage it"
        ),
        detail={"handle": claimed},
    )


def _append_staged(
    rs: Any,
    staged: list[tuple[int, str, str]],
    claimed: int,
    leg_label: str,
    producer: str,
    *,
    before: Collection[int],
    extra: Collection[int] = (),
    expect_label: str | bytes,
    expect_token: bool,
) -> None:
    """Adopt *claimed* into *staged* (R3F2: null/alias/pre-existing fail).

    *extra* covers live adopted handles outside *staged* (a derive
    base, unwrap transient keys): an output aliasing any of them is
    the same proved contradiction. A novel handle is correlated
    against *expect_label*/*expect_token* before staging (R4-F1).
    """
    staged.append(
        (
            _adopt_staged(
                rs,
                claimed,
                label=leg_label,
                producer_operation=producer,
                before=before,
                siblings=[*[h for h, _, _ in staged], *extra],
                expect_label=expect_label,
                expect_token=expect_token,
            ),
            leg_label,
            producer,
        )
    )


def _append_keypair_halves(
    rs: Any,
    staged: list[tuple[int, str, str]],
    pub: int,
    priv: int,
    pub_label: str,
    priv_label: str,
    producer: str,
    *,
    before: Collection[int],
    expect_pub_label: str | bytes,
    expect_priv_label: str | bytes,
) -> None:
    """Adopt a generated pair: pair-aliasing fails before correlation (R4-F1).

    The halves share one producer return, so an aliased pair is a
    proved contradiction even when the handle itself is unreadable
    (per-half adoption would void on the first half before the alias
    manifests). Each half then correlates like any staged output.
    """
    if pub and pub == priv:
        C.fail_as(
            "self_contradiction",
            kind="policy",
            label=pub_label,
            operation=producer,
            inherit_mechanism=False,
            actual=int(CKR_OK),
            summary=(
                f"{pub_label}: {producer} returned aliased halves ({pub}); refusing to stage them"
            ),
            detail={"halves": [pub, priv]},
        )
    _append_staged(
        rs,
        staged,
        pub,
        pub_label,
        producer,
        before=before,
        expect_label=expect_pub_label,
        expect_token=False,
    )
    _append_staged(
        rs,
        staged,
        priv,
        priv_label,
        producer,
        before=before,
        expect_label=expect_priv_label,
        expect_token=False,
    )


def _stage_created_objects(rs: Any) -> list[tuple[int, str, str]]:
    """Three C_CreateObject routes: data, imported AES, imported RSA public."""
    from cryptography.hazmat.primitives.asymmetric import rsa

    skip_unless_create_object_supported(rs)
    before = _baseline_or_void(rs, label="CKA_UNIQUE_ID created staging")
    staged: list[tuple[int, str, str]] = []
    try:
        data = create_object(
            rs.raw,
            rs.sh,
            {
                CKA_CLASS: CKO_DATA,
                CKA_VALUE: b"qc7c-data",
                CKA_TOKEN: False,
                CKA_LABEL: "qc7c-created-data",
            },
        )
        _append_staged(
            rs,
            staged,
            data,
            "CKA_UNIQUE_ID:created data object",
            "C_CreateObject",
            before=before,
            expect_label="qc7c-created-data",
            expect_token=False,
        )
        secret = import_secret_key(
            rs.raw,
            rs.sh,
            CKK_AES,
            bytes(range(16)),
            attrs={CKA_LABEL: "qc7c-created-aes", CKA_TOKEN: False},
        )
        _append_staged(
            rs,
            staged,
            secret,
            "CKA_UNIQUE_ID:imported AES key",
            "C_CreateObject",
            before=before,
            expect_label="qc7c-created-aes",
            expect_token=False,
        )
        numbers = rsa.generate_private_key(65537, 2048).public_key().public_numbers()
        rsa_pub = create_object(
            rs.raw,
            rs.sh,
            {
                CKA_CLASS: CKO_PUBLIC_KEY,
                CKA_KEY_TYPE: CKK_RSA,
                CKA_MODULUS: numbers.n.to_bytes((numbers.n.bit_length() + 7) // 8, "big"),
                CKA_PUBLIC_EXPONENT: numbers.e.to_bytes((numbers.e.bit_length() + 7) // 8, "big"),
                CKA_TOKEN: False,
                CKA_VERIFY: True,
                CKA_LABEL: "qc7c-created-rsa",
            },
        )
        _append_staged(
            rs,
            staged,
            rsa_pub,
            "CKA_UNIQUE_ID:imported RSA public key",
            "C_CreateObject",
            before=before,
            expect_label="qc7c-created-rsa",
            expect_token=False,
        )
    except BaseException:
        _destroy_all(rs, [h for h, _, _ in staged])
        raise
    return staged


def _stage_generated_objects(rs: Any) -> list[tuple[int, str, str]]:
    before = _baseline_or_void(rs, label="CKA_UNIQUE_ID generated staging")
    staged: list[tuple[int, str, str]] = []
    try:
        first = gen_aes_key_or_xfail(
            rs,
            bits=128,
            attrs={CKA_LABEL: "qc7c-gen-aes-1", CKA_TOKEN: False},
            purpose="QC7c generated IDs",
        )
        _append_staged(
            rs,
            staged,
            first,
            "CKA_UNIQUE_ID:generated AES key 1",
            "C_GenerateKey",
            before=before,
            expect_label="qc7c-gen-aes-1",
            expect_token=False,
        )
        second = gen_aes_key_or_xfail(
            rs,
            bits=128,
            attrs={CKA_LABEL: "qc7c-gen-aes-2", CKA_TOKEN: False},
            purpose="QC7c generated IDs",
        )
        _append_staged(
            rs,
            staged,
            second,
            "CKA_UNIQUE_ID:generated AES key 2",
            "C_GenerateKey",
            before=before,
            expect_label="qc7c-gen-aes-2",
            expect_token=False,
        )
        pub, priv = gen_rsa_keypair_or_xfail(
            rs,
            2048,
            public_attrs={CKA_LABEL: "qc7c-gen-rsa-pub", CKA_TOKEN: False},
            private_attrs={CKA_LABEL: "qc7c-gen-rsa-priv", CKA_TOKEN: False},
        )
        _append_keypair_halves(
            rs,
            staged,
            pub,
            priv,
            "CKA_UNIQUE_ID:generated RSA public half",
            "CKA_UNIQUE_ID:generated RSA private half",
            "C_GenerateKeyPair",
            before=before,
            expect_pub_label="qc7c-gen-rsa-pub",
            expect_priv_label="qc7c-gen-rsa-priv",
        )
    except BaseException:
        _destroy_all(rs, [h for h, _, _ in staged])
        raise
    return staged


