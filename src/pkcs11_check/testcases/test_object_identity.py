"""CKA_UNIQUE_ID generation, uniqueness, copy and override tests (QC7c).

PKCS#11 v3.2 section 4.4.1: any time a new object is created, a value
for CKA_UNIQUE_ID MUST be generated by the token and stored with the
object; values are unique among simultaneously visible objects; a copy
gets its own ID; a template that specifies the attribute fails with
CKR_ATTRIBUTE_READ_ONLY. CKA_UNIQUE_ID was introduced in PKCS#11 v3.0,
so the whole file skips visibly below cryptokiVersion 3.0 and makes no
claim for pre-3.0 tokens. Nonreuse across token resets is not required.

Bounded creator set: C_CreateObject, C_GenerateKey, C_GenerateKeyPair
(both halves), C_CopyObject, and ML-KEM encapsulate/decapsulate outputs
where advertised. Derive/Unwrap creators are an explicit residual
(owned by other tasks' files). A non-UTF8 ID is judged as an opaque
byte string: uniqueness/nonemptiness on the raw bytes. Records carry
lengths only, never ID bytes.
"""

