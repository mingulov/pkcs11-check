def _fixed_bytes(n: int, seed: int = 42) -> bytes:
    """Deterministic bytes for reproducible vectors."""
    import hashlib

    result = b""
    counter = seed
    while len(result) < n:
        result += hashlib.sha256(counter.to_bytes(8, "big")).digest()
        counter += 1
    return result[:n]


def generate_aes_ecb() -> dict:
    from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

    vectors = []
    for bits in (128, 192, 256):
        key = _fixed_bytes(bits // 8, seed=100 + bits)
        plaintext = _fixed_bytes(32, seed=200 + bits)  # 2 blocks
        cipher = Cipher(algorithms.AES(key), modes.ECB())
        enc = cipher.encryptor()
        ct = enc.update(plaintext) + enc.finalize()
        vectors.append(
            {
                "id": f"aes_ecb_{bits}_2blocks",
                "type": "positive",
                "key_bits": bits,
                "key_hex": key.hex(),
                "params": {},
                "plaintext_hex": plaintext.hex(),
                "ciphertext_hex": ct.hex(),
            }
        )
    return {
        "mechanism": "CKM_AES_ECB",
        "family": "aes",
        "key_type": "CKK_AES",
        "source": "generated by scripts/generate_mechanism_vectors.py",
        "vectors": vectors,
    }


