def _i2b(n: int, length: int) -> str:
    """Convert integer to big-endian hex string of given byte length."""
    return n.to_bytes(length, "big").hex()


def generate_rsa_pkcs1_sha256() -> dict:
    from cryptography.hazmat.primitives import hashes
    from cryptography.hazmat.primitives.asymmetric import padding, rsa

    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    priv = key.private_numbers()
    pub = key.public_key().public_numbers()
    key_bytes = (pub.n.bit_length() + 7) // 8

    messages = [b"", b"hello", b"A" * 245]
    vectors = []
    for i, msg in enumerate(messages):
        sig = key.sign(msg, padding.PKCS1v15(), hashes.SHA256())
        vectors.append(
            {
                "id": f"rsa_pkcs1_sha256_{i}",
                "type": "positive",
                "mechanism_name": "CKM_SHA256_RSA_PKCS",
                "key_type": "asymmetric",
                "key_bits": 2048,
                "n_hex": _i2b(pub.n, key_bytes),
                "e_hex": _i2b(pub.e, (pub.e.bit_length() + 7) // 8),
                "d_hex": _i2b(priv.d, key_bytes),
                "p_hex": _i2b(priv.p, (priv.p.bit_length() + 7) // 8),
                "q_hex": _i2b(priv.q, (priv.q.bit_length() + 7) // 8),
                "dmp1_hex": _i2b(priv.dmp1, (priv.dmp1.bit_length() + 7) // 8),
                "dmq1_hex": _i2b(priv.dmq1, (priv.dmq1.bit_length() + 7) // 8),
                "iqmp_hex": _i2b(priv.iqmp, (priv.iqmp.bit_length() + 7) // 8),
                "input_hex": msg.hex(),
                "signature_hex": sig.hex(),
                "params": {},
            }
        )
    return {
        "mechanism": "CKM_SHA256_RSA_PKCS",
        "family": "rsa_pkcs1_sha256",
        "key_type": "CKK_RSA",
        "source": "generated by scripts/generate_mechanism_vectors.py",
        "vectors": vectors,
    }


