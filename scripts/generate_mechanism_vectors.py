def _des3_cmac_material() -> tuple[bytes, bytes, bytes]:
    """Return deterministic 3DES CMAC vector material."""
    from cryptography.hazmat.decrepit.ciphers.algorithms import TripleDES
    from cryptography.hazmat.primitives.cmac import CMAC

    key = _fixed_bytes(24, seed=1800)
    data = _fixed_bytes(23, seed=1950)
    cmac = CMAC(TripleDES(key))
    cmac.update(data)
    return key, data, cmac.finalize()


