def generate_aes_gcm() -> dict:
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM

    vectors = []
    for bits in (128, 192, 256):
        key = _fixed_bytes(bits // 8, seed=600 + bits)
        iv = _fixed_bytes(12, seed=700 + bits)
        plaintext = _fixed_bytes(32, seed=800 + bits)
        aad = _fixed_bytes(16, seed=900 + bits)
        aesgcm = AESGCM(key)
        ct_tag = aesgcm.encrypt(iv, plaintext, aad)
        ct = ct_tag[:-16]
        tag = ct_tag[-16:]
        vectors.append(
            {
                "id": f"aes_gcm_{bits}_with_aad",
                "type": "positive",
                "key_bits": bits,
                "key_hex": key.hex(),
                "params": {"iv_hex": iv.hex(), "aad_hex": aad.hex(), "tag_bits": 128},
                "plaintext_hex": plaintext.hex(),
                "ciphertext_hex": ct.hex(),
                "tag_hex": tag.hex(),
            }
        )
        # Also without AAD
        ct_tag2 = aesgcm.encrypt(iv, plaintext, None)
        vectors.append(
            {
                "id": f"aes_gcm_{bits}_no_aad",
                "type": "positive",
                "key_bits": bits,
                "key_hex": key.hex(),
                "params": {"iv_hex": iv.hex(), "aad_hex": "", "tag_bits": 128},
                "plaintext_hex": plaintext.hex(),
                "ciphertext_hex": ct_tag2[:-16].hex(),
                "tag_hex": ct_tag2[-16:].hex(),
            }
        )
    return {
        "mechanism": "CKM_AES_GCM",
        "family": "aes",
        "key_type": "CKK_AES",
        "source": "generated by scripts/generate_mechanism_vectors.py",
        "vectors": vectors,
    }


def generate_sha() -> dict:
    import hashlib

    vectors = []
    test_inputs = [
        ("empty", b""),
        ("abc", b"abc"),
        ("long", b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"),
    ]
    for algo, name, digest_len in [
        ("sha1", "SHA_1", 20),
        ("sha224", "SHA224", 28),
        ("sha256", "SHA256", 32),
        ("sha384", "SHA384", 48),
        ("sha512", "SHA512", 64),
    ]:
        for input_id, input_data in test_inputs:
            h = hashlib.new(algo)
            h.update(input_data)
            vectors.append(
                {
                    "id": f"{name}_{input_id}",
                    "type": "positive",
                    "mechanism_name": f"CKM_{name}",
                    "input_hex": input_data.hex(),
                    "digest_hex": h.hexdigest(),
                    "digest_len": digest_len,
                }
            )
    return {
        "mechanism": "CKM_SHA_*",
        "family": "sha",
        "key_type": None,
        "source": "generated by scripts/generate_mechanism_vectors.py",
        "vectors": vectors,
    }


def generate_hmac() -> dict:
    import hmac

    vectors = []
    for algo, name, key_len in [
        ("sha256", "SHA256_HMAC", 32),
        ("sha384", "SHA384_HMAC", 48),
        ("sha512", "SHA512_HMAC", 64),
    ]:
        key = _fixed_bytes(key_len, seed=1000 + key_len)
        data = _fixed_bytes(64, seed=1100 + key_len)
        mac = hmac.new(key, data, algo).digest()
        vectors.append(
            {
                "id": f"{name}_basic",
                "type": "positive",
                "mechanism_name": f"CKM_{name}",
                "key_hex": key.hex(),
                "key_bits": key_len * 8,
                "input_hex": data.hex(),
                "mac_hex": mac.hex(),
            }
        )
    return {
        "mechanism": "CKM_SHA*_HMAC",
        "family": "hmac",
        "key_type": "CKK_GENERIC_SECRET",
        "source": "generated by scripts/generate_mechanism_vectors.py",
        "vectors": vectors,
    }


def generate_aes_cbc_pad() -> dict:
    from cryptography.hazmat.primitives import padding
    from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

    vectors = []
    for bits in (128, 192, 256):
        key = _fixed_bytes(bits // 8, seed=1200 + bits)
        iv = _fixed_bytes(16, seed=1300 + bits)
        plaintext = _fixed_bytes(31, seed=1400 + bits)  # non-block-aligned to test padding
        padder = padding.PKCS7(128).padder()
        padded = padder.update(plaintext) + padder.finalize()
        cipher = Cipher(algorithms.AES(key), modes.CBC(iv))
        enc = cipher.encryptor()
        ct = enc.update(padded) + enc.finalize()
        vectors.append(
            {
                "id": f"aes_cbc_pad_{bits}_31bytes",
                "type": "positive",
                "key_bits": bits,
                "key_hex": key.hex(),
                "params": {"iv_hex": iv.hex()},
                "plaintext_hex": plaintext.hex(),
                "ciphertext_hex": ct.hex(),
            }
        )
    return {
        "mechanism": "CKM_AES_CBC_PAD",
        "family": "aes",
        "key_type": "CKK_AES",
        "source": "generated by scripts/generate_mechanism_vectors.py",
        "vectors": vectors,
    }


