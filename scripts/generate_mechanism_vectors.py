def generate_aes_gcm() -> dict:
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM

    vectors = []
    for bits in (128, 192, 256):
        key = _fixed_bytes(bits // 8, seed=600 + bits)
        iv = _fixed_bytes(12, seed=700 + bits)
        plaintext = _fixed_bytes(32, seed=800 + bits)
        aad = _fixed_bytes(16, seed=900 + bits)
        aesgcm = AESGCM(key)
        ct_tag = aesgcm.encrypt(iv, plaintext, aad)
        ct = ct_tag[:-16]
        tag = ct_tag[-16:]
        vectors.append(
            {
                "id": f"aes_gcm_{bits}_with_aad",
                "type": "positive",
                "key_bits": bits,
                "key_hex": key.hex(),
                "params": {"iv_hex": iv.hex(), "aad_hex": aad.hex(), "tag_bits": 128},
                "plaintext_hex": plaintext.hex(),
                "ciphertext_hex": ct.hex(),
                "tag_hex": tag.hex(),
            }
        )
        # Also without AAD
        ct_tag2 = aesgcm.encrypt(iv, plaintext, None)
        vectors.append(
            {
                "id": f"aes_gcm_{bits}_no_aad",
                "type": "positive",
                "key_bits": bits,
                "key_hex": key.hex(),
                "params": {"iv_hex": iv.hex(), "aad_hex": "", "tag_bits": 128},
                "plaintext_hex": plaintext.hex(),
                "ciphertext_hex": ct_tag2[:-16].hex(),
                "tag_hex": ct_tag2[-16:].hex(),
            }
        )
    return {
        "mechanism": "CKM_AES_GCM",
        "family": "aes",
        "key_type": "CKK_AES",
        "source": "generated by scripts/generate_mechanism_vectors.py",
        "vectors": vectors,
    }


