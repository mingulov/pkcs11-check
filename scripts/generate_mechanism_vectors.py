def _openssl_evp_setup(libcrypto: object) -> bool:
    """Set up argtypes/restype on OpenSSL EVP functions to avoid ctypes marshalling segfaults."""
    import ctypes

    libcrypto.EVP_CIPHER_CTX_new.restype = ctypes.c_void_p
    libcrypto.EVP_CIPHER_CTX_new.argtypes = []

    libcrypto.EVP_CIPHER_CTX_free.restype = None
    libcrypto.EVP_CIPHER_CTX_free.argtypes = [ctypes.c_void_p]

    libcrypto.EVP_get_cipherbyname.restype = ctypes.c_void_p
    libcrypto.EVP_get_cipherbyname.argtypes = [ctypes.c_char_p]

    libcrypto.EVP_EncryptInit_ex.restype = ctypes.c_int
    libcrypto.EVP_EncryptInit_ex.argtypes = [
        ctypes.c_void_p,  # ctx
        ctypes.c_void_p,  # cipher
        ctypes.c_void_p,  # engine (NULL)
        ctypes.c_char_p,  # key
        ctypes.c_char_p,  # iv
    ]

    libcrypto.EVP_CIPHER_CTX_set_padding.restype = ctypes.c_int
    libcrypto.EVP_CIPHER_CTX_set_padding.argtypes = [ctypes.c_void_p, ctypes.c_int]

    libcrypto.EVP_EncryptUpdate.restype = ctypes.c_int
    libcrypto.EVP_EncryptUpdate.argtypes = [
        ctypes.c_void_p,
        ctypes.c_char_p,
        ctypes.POINTER(ctypes.c_int),
        ctypes.c_char_p,
        ctypes.c_int,
    ]

    libcrypto.EVP_EncryptFinal_ex.restype = ctypes.c_int
    libcrypto.EVP_EncryptFinal_ex.argtypes = [
        ctypes.c_void_p,
        ctypes.c_char_p,
        ctypes.POINTER(ctypes.c_int),
    ]
    return True


def _openssl_encrypt(
    libcrypto: object,
    cipher_name: bytes,
    key: bytes,
    iv: bytes | None,
    plaintext: bytes,
) -> bytes:
    """Encrypt plaintext using an OpenSSL EVP cipher (no padding, block-aligned input)."""
    import ctypes

    cipher = libcrypto.EVP_get_cipherbyname(cipher_name)
    if not cipher:
        return b""
    ctx = libcrypto.EVP_CIPHER_CTX_new()
    try:
        libcrypto.EVP_EncryptInit_ex(ctx, cipher, None, key, iv)
        libcrypto.EVP_CIPHER_CTX_set_padding(ctx, 0)
        outbuf = ctypes.create_string_buffer(len(plaintext) + 16)
        outlen = ctypes.c_int(0)
        libcrypto.EVP_EncryptUpdate(
            ctx, outbuf, ctypes.byref(outlen), plaintext, len(plaintext)
        )
        total = outlen.value
        libcrypto.EVP_EncryptFinal_ex(
            ctx,
            ctypes.cast(ctypes.addressof(outbuf) + total, ctypes.c_char_p),
            ctypes.byref(outlen),
        )
        total += outlen.value
        return outbuf.raw[:total]
    finally:
        libcrypto.EVP_CIPHER_CTX_free(ctx)


