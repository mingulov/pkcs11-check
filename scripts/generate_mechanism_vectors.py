def _openssl_evp_setup(libcrypto: object) -> bool:
    """Set up argtypes/restype on OpenSSL EVP functions to avoid ctypes marshalling segfaults."""
    import ctypes

    libcrypto.EVP_CIPHER_CTX_new.restype = ctypes.c_void_p
    libcrypto.EVP_CIPHER_CTX_new.argtypes = []

    libcrypto.EVP_CIPHER_CTX_free.restype = None
    libcrypto.EVP_CIPHER_CTX_free.argtypes = [ctypes.c_void_p]

    libcrypto.EVP_get_cipherbyname.restype = ctypes.c_void_p
    libcrypto.EVP_get_cipherbyname.argtypes = [ctypes.c_char_p]

    libcrypto.EVP_EncryptInit_ex.restype = ctypes.c_int
    libcrypto.EVP_EncryptInit_ex.argtypes = [
        ctypes.c_void_p,  # ctx
        ctypes.c_void_p,  # cipher
        ctypes.c_void_p,  # engine (NULL)
        ctypes.c_char_p,  # key
        ctypes.c_char_p,  # iv
    ]

    libcrypto.EVP_CIPHER_CTX_set_padding.restype = ctypes.c_int
    libcrypto.EVP_CIPHER_CTX_set_padding.argtypes = [ctypes.c_void_p, ctypes.c_int]

    libcrypto.EVP_EncryptUpdate.restype = ctypes.c_int
    libcrypto.EVP_EncryptUpdate.argtypes = [
        ctypes.c_void_p,
        ctypes.c_char_p,
        ctypes.POINTER(ctypes.c_int),
        ctypes.c_char_p,
        ctypes.c_int,
    ]

    libcrypto.EVP_EncryptFinal_ex.restype = ctypes.c_int
    libcrypto.EVP_EncryptFinal_ex.argtypes = [
        ctypes.c_void_p,
        ctypes.c_char_p,
        ctypes.POINTER(ctypes.c_int),
    ]
    return True


def _openssl_encrypt(
    libcrypto: object,
    cipher_name: bytes,
    key: bytes,
    iv: bytes | None,
    plaintext: bytes,
) -> bytes:
    """Encrypt plaintext using an OpenSSL EVP cipher (no padding, block-aligned input)."""
    import ctypes

    cipher = libcrypto.EVP_get_cipherbyname(cipher_name)
    if not cipher:
        return b""
    ctx = libcrypto.EVP_CIPHER_CTX_new()
    try:
        libcrypto.EVP_EncryptInit_ex(ctx, cipher, None, key, iv)
        libcrypto.EVP_CIPHER_CTX_set_padding(ctx, 0)
        outbuf = ctypes.create_string_buffer(len(plaintext) + 16)
        outlen = ctypes.c_int(0)
        libcrypto.EVP_EncryptUpdate(ctx, outbuf, ctypes.byref(outlen), plaintext, len(plaintext))
        total = outlen.value
        libcrypto.EVP_EncryptFinal_ex(
            ctx,
            ctypes.cast(ctypes.addressof(outbuf) + total, ctypes.c_char_p),
            ctypes.byref(outlen),
        )
        total += outlen.value
        return outbuf.raw[:total]
    finally:
        libcrypto.EVP_CIPHER_CTX_free(ctx)


def generate_aria_ecb() -> dict:
    """ARIA ECB vectors via OpenSSL EVP (ctypes)."""
    import ctypes
    import ctypes.util

    libcrypto_path = ctypes.util.find_library("crypto")
    if not libcrypto_path:
        return {
            "mechanism": "CKM_ARIA_ECB",
            "family": "aria_ecb",
            "key_type": "CKK_ARIA",
            "source": "skipped: libcrypto not found",
            "vectors": [],
        }

    libcrypto = ctypes.CDLL(libcrypto_path)
    _openssl_evp_setup(libcrypto)

    vectors = []
    for bits in (128, 192, 256):
        key = _fixed_bytes(bits // 8, seed=6000 + bits)
        pt = _fixed_bytes(32, seed=6100 + bits)  # 2 blocks
        cipher_name = f"aria-{bits}-ecb".encode()
        ct = _openssl_encrypt(libcrypto, cipher_name, key, None, pt)
        if not ct:
            continue
        vectors.append(
            {
                "id": f"aria_ecb_{bits}",
                "type": "positive",
                "mechanism_name": "CKM_ARIA_ECB",
                "key_type": "symmetric",
                "key_hex": key.hex(),
                "key_bits": bits,
                "plaintext_hex": pt.hex(),
                "ciphertext_hex": ct.hex(),
                "params": {},
            }
        )
    return {
        "mechanism": "CKM_ARIA_ECB",
        "family": "aria_ecb",
        "key_type": "CKK_ARIA",
        "source": "generated via OpenSSL EVP ctypes",
        "vectors": vectors,
    }


def generate_des_ecb() -> dict:
    """DES-ECB (single DES) vectors.

    Single DES is not in the cryptography library as a public API; DES in
    OpenSSL 3 requires the legacy provider.  We compute single-DES by
    instantiating TripleDES with K1=K2=K3 (the 8-byte key repeated 3 times),
    which is mathematically equivalent to single DES and produces identical
    output.  Only the 8-byte key is stored in the JSON — it is what PKCS#11
    hardware receives for CKM_DES_ECB.

    DES key = 8 bytes (56-bit effective), block = 8 bytes.
    """
    from cryptography.hazmat.decrepit.ciphers.algorithms import TripleDES
    from cryptography.hazmat.primitives.ciphers import Cipher, modes

    key8 = _fixed_bytes(8, seed=8000)  # 8-byte DES key
    key24 = key8 * 3  # K1=K2=K3 → equivalent to single DES
    pt = _fixed_bytes(16, seed=8100)  # 2 DES blocks (8 bytes each)
    cipher = Cipher(TripleDES(key24), modes.ECB())
    enc = cipher.encryptor()
    ct = enc.update(pt) + enc.finalize()
    vectors = [
        {
            "id": "des_ecb_64_2blocks",
            "type": "positive",
            "mechanism_name": "CKM_DES_ECB",
            "key_type": "symmetric",
            "key_bits": 64,
            "key_hex": key8.hex(),
            "params": {},
            "plaintext_hex": pt.hex(),
            "ciphertext_hex": ct.hex(),
        }
    ]
    return {
        "mechanism": "CKM_DES_ECB",
        "family": "des_ecb",
        "key_type": "CKK_DES",
        "source": "generated by scripts/generate_mechanism_vectors.py (TripleDES K1=K2=K3)",
        "vectors": vectors,
    }


