def generate_aes_ofb() -> dict:
    from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

    vectors = []
    for bits in (128, 192, 256):
        key = _fixed_bytes(bits // 8, seed=4000 + bits)
        iv = _fixed_bytes(16, seed=4100 + bits)
        plaintext = _fixed_bytes(32, seed=4200 + bits)
        cipher = Cipher(algorithms.AES(key), modes.OFB(iv))
        enc = cipher.encryptor()
        ct = enc.update(plaintext) + enc.finalize()
        vectors.append(
            {
                "id": f"aes_ofb_{bits}_32bytes",
                "type": "positive",
                "mechanism_name": "CKM_AES_OFB",
                "key_type": "symmetric",
                "key_bits": bits,
                "key_hex": key.hex(),
                "params": {"iv_hex": iv.hex()},
                "plaintext_hex": plaintext.hex(),
                "ciphertext_hex": ct.hex(),
            }
        )
    return {
        "mechanism": "CKM_AES_OFB",
        "family": "aes_ofb",
        "key_type": "CKK_AES",
        "source": "generated by scripts/generate_mechanism_vectors.py",
        "vectors": vectors,
    }


