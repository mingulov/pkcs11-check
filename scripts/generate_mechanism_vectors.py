def generate_des_ecb() -> dict:
    """DES-ECB (single DES) vectors.

    Single DES is not in the cryptography library as a public API; DES in
    OpenSSL 3 requires the legacy provider.  We compute single-DES by
    instantiating TripleDES with K1=K2=K3 (the 8-byte key repeated 3 times),
    which is mathematically equivalent to single DES and produces identical
    output.  Only the 8-byte key is stored in the JSON — it is what PKCS#11
    hardware receives for CKM_DES_ECB.

    DES key = 8 bytes (56-bit effective), block = 8 bytes.
    """
    from cryptography.hazmat.decrepit.ciphers.algorithms import TripleDES
    from cryptography.hazmat.primitives.ciphers import Cipher, modes

    key8 = _fixed_bytes(8, seed=8000)  # 8-byte DES key
    key24 = key8 * 3  # K1=K2=K3 → equivalent to single DES
    pt = _fixed_bytes(16, seed=8100)  # 2 DES blocks (8 bytes each)
    cipher = Cipher(TripleDES(key24), modes.ECB())
    enc = cipher.encryptor()
    ct = enc.update(pt) + enc.finalize()
    vectors = [
        {
            "id": "des_ecb_64_2blocks",
            "type": "positive",
            "mechanism_name": "CKM_DES_ECB",
            "key_type": "symmetric",
            "key_bits": 64,
            "key_hex": key8.hex(),
            "params": {},
            "plaintext_hex": pt.hex(),
            "ciphertext_hex": ct.hex(),
        }
    ]
    return {
        "mechanism": "CKM_DES_ECB",
        "family": "des_ecb",
        "key_type": "CKK_DES",
        "source": "generated by scripts/generate_mechanism_vectors.py (TripleDES K1=K2=K3)",
        "vectors": vectors,
    }


