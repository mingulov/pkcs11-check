def main() -> None:
    parser = argparse.ArgumentParser(description="Generate mechanism KAT vectors")
    parser.add_argument("--all", action="store_true", help="Generate all families")
    parser.add_argument("--family", type=str, help="Generate specific family")
    args = parser.parse_args()

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    if args.all:
        families = list(GENERATORS.keys())
    elif args.family:
        families = [args.family]
    else:
        parser.print_help()
        sys.exit(1)

    for family in families:
        gen = GENERATORS.get(family)
        if gen is None:
            print(f"Unknown family: {family}", file=sys.stderr)
            continue
        data = gen()
        path = OUTPUT_DIR / f"{family}.json"
        path.write_text(json.dumps(data, indent=2) + "\n")
        print(f"Generated {path} ({len(data['vectors'])} vectors)")


if __name__ == "__main__":
    main()
