def generate_ecdsa_sha1() -> dict:
    """ECDSA-SHA1 vectors on P-256 (secp256r1).

    verify_only=True: the test imports the fixed key and verifies the signature.
    """
    from cryptography.hazmat.primitives import hashes
    from cryptography.hazmat.primitives.asymmetric import ec
    from cryptography.hazmat.primitives.asymmetric.utils import decode_dss_signature

    key = ec.generate_private_key(ec.SECP256R1())
    priv_numbers = key.private_numbers()
    scalar_size = 32
    scalar_hex = _i2b(priv_numbers.private_value, scalar_size)
    # P-256 OID in DER: OBJECT IDENTIFIER 1.2.840.10045.3.1.7
    ec_params_hex = "06082a8648ce3d030107"

    messages = [b"", b"hello", _fixed_bytes(100, seed=9300)]
    vectors = []
    for i, msg in enumerate(messages):
        sig_der = key.sign(msg, ec.ECDSA(hashes.SHA1()))
        r, s = decode_dss_signature(sig_der)
        sig_p11 = r.to_bytes(scalar_size, "big") + s.to_bytes(scalar_size, "big")
        vectors.append(
            {
                "id": f"ecdsa_sha1_{i}",
                "type": "positive",
                "mechanism_name": "CKM_ECDSA_SHA1",
                "key_type": "asymmetric",
                "ec_params_hex": ec_params_hex,
                "ec_private_scalar_hex": scalar_hex,
                "input_hex": msg.hex(),
                "signature_hex": sig_p11.hex(),
                "verify_only": True,
                "params": {},
            }
        )
    return {
        "mechanism": "CKM_ECDSA_SHA1",
        "family": "ecdsa_sha1",
        "key_type": "CKK_EC",
        "source": "generated by scripts/generate_mechanism_vectors.py",
        "vectors": vectors,
    }


