def _openssl_enc(cipher_name: str, key: bytes, plaintext: bytes, iv: bytes | None = None) -> bytes:
    """Run OpenSSL enc for legacy ciphers that cryptography does not expose."""
    cmd = [
        "openssl",
        "enc",
        f"-{cipher_name}",
        "-nopad",
        "-nosalt",
        "-K",
        key.hex(),
        "-provider",
        "legacy",
        "-provider",
        "default",
    ]
    if iv is not None:
        cmd.extend(["-iv", iv.hex()])
    proc = subprocess.run(
        cmd,
        input=plaintext,
        capture_output=True,
        check=True,
    )
    return proc.stdout


