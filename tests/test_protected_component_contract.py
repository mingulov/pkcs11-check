def test_matrix_enumerates_ten_families() -> None:
    assert sorted(_families()) == [
        "aes",
        "dh",
        "ec",
        "edwards",
        "mldsa",
        "mlkem",
        "montgomery",
        "rsa",
        "slhdsa",
        "x942",
    ]
    for family in _families().values():
        assert family.spec_ref, family.family
        assert family.creations == ("gen", "import"), family.family
        assert family.keygen_mechanism, family.family
        assert family.family_mechanisms, family.family


def test_matrix_rsa_components() -> None:
    rsa = _families()["rsa"]
    protected = {comp.attr: comp.mandatory for comp in rsa.protected}
    assert protected == {
        int(CKA_PRIVATE_EXPONENT): True,
        int(CKA_PRIME_1): False,
        int(CKA_PRIME_2): False,
        int(CKA_EXPONENT_1): False,
        int(CKA_EXPONENT_2): False,
        int(CKA_COEFFICIENT): False,
    }
    assert int(CKA_PUBLIC_EXPONENT) not in protected
    assert int(CKA_PUBLIC_EXPONENT) in [int(a) for a in rsa.public]


@pytest.mark.parametrize("family_id", ["ec", "edwards", "montgomery"])
def test_matrix_ec_family_value_only(family_id: str) -> None:
    family = _families()[family_id]
    assert [(c.attr, c.mandatory) for c in family.protected] == [(int(CKA_VALUE), True)]
    assert [int(a) for a in family.public] == [int(CKA_EC_PARAMS)]


@pytest.mark.parametrize("family_id", ["dh", "x942"])
def test_matrix_finite_field_value(family_id: str) -> None:
    family = _families()[family_id]
    assert [(c.attr, c.mandatory) for c in family.protected] == [(int(CKA_VALUE), True)]
    expected_public = {
        "dh": [int(CKA_PRIME), int(CKA_BASE)],
        "x942": [int(CKA_PRIME), int(CKA_SUBPRIME), int(CKA_BASE)],
    }[family_id]
    assert [int(a) for a in family.public] == expected_public


@pytest.mark.parametrize("family_id", ["mldsa", "mlkem"])
def test_matrix_ml_seed_and_value(family_id: str) -> None:
    family = _families()[family_id]
    protected = {comp.attr: comp.mandatory for comp in family.protected}
    assert protected == {int(CKA_VALUE): True, int(CKA_SEED): False}
    # The seed row uses the tree's own CKA_SEED table entry, not an invention.
    assert int(CKA_SEED) == 0x637


def test_matrix_slh_value_only_no_seed() -> None:
    slh = _families()["slhdsa"]
    assert [(c.attr, c.mandatory) for c in slh.protected] == [(int(CKA_VALUE), True)]
    assert int(CKA_SEED) not in [int(a) for a in slh.public]


def test_matrix_aes_value_only() -> None:
    aes = _families()["aes"]
    assert [(c.attr, c.mandatory) for c in aes.protected] == [(int(CKA_VALUE), True)]


def test_matrix_uses_only_tree_defined_attribute_ids() -> None:
    for family in _families().values():
        for comp in family.protected:
            assert int(comp.attr) in ATTR_VALUE_TYPES, (family.family, hex(int(comp.attr)))
        for attr in family.public:
            assert int(attr) in ATTR_VALUE_TYPES, (family.family, hex(int(attr)))


