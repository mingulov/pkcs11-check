def _assert_runs(fn: Any, *args: Any, **kwargs: Any) -> None:
    """Call ``fn`` and fail (visibly) if it skips or xfails instead of passing."""
    try:
        fn(*args, **kwargs)
    except pytest.skip.Exception as exc:
        pytest.fail(f"expected {fn} to run, but it skipped: {exc}")
    except pytest.xfail.Exception as exc:
        pytest.fail(f"expected {fn} to pass, but it xfailed: {exc}")


