# Behavior tags understood by _MatrixFake. Tuple forms carry a payload:
# ("generated", n) answers n fixed bytes, ("fixed", data) answers data,
# ("query_only", rv, length) fails only the size query, ("untouched", rv)
# leaves ulValueLen unassigned, ("refuse32", rv) refuses with the 32-bit
# sentinel, ("len_only", n) reports a length without writing, ("overlong",
# reported) writes the secret but reports a longer length, ("varying",)
# answers inconsistent bytes per call, ("planted_const", byte, pos) writes a
# constant fill with one planted byte, ("partial", k) copies k secret bytes,
# ("slice", off, k) copies secret[off:off+k] at its offset, ("reread", rv)
# answers generated bytes but the 0x5A verification reread with rv,
# ("const_fill", rv, byte, n) refuses with an n-byte constant fill,
# ("const_rv", rv, byte, pos) like planted_const but with return rv,
# ("query_fail_data_ok", rv) fails the size query yet delivers on data,
# ("data_fail", rv) refuses only the data call with untouched outputs,
# ("slice_fill", off, k, byte) copies secret[off:off+k] at its offset over
# a constant background fill, ("reread_len", first_len, rv) answers the
# first data read with first_len but the 0x5A verification reread with rv,
# ("query_ok_const", rv, byte, n) answers the size query with OK yet the
# data call with rv plus a constant fill, ("query_ok_data_fail", rv)
# answers the size query with OK yet refuses the data call untouched.
Behavior = str | tuple[Any, ...]


def _fill_handle(out: Any, value: int) -> None:
    """Write an out-handle passed as ``byref(ctypes_scalar)``."""
    ctypes.cast(out, ctypes.POINTER(ctypes.c_ulong)).contents.value = value


class _MatrixFake:
    """Scriptable fake token for the QC1 protected-read matrix.

    The fake captures every creation template, so "readable" behaviors
    answer the exact bytes production stored -- the same material a real
    token would hold. Attributes never supplied (an unstored optional
    seed) honestly answer ``CKR_ATTRIBUTE_TYPE_INVALID``.
    """

    # noqa comments below: raw PKCS#11 entry-point names are mandated.

    def __init__(
        self,
        behaviors: dict[int, Behavior] | None = None,
        *,
        claim: bytes = b"\x01",
        mixed: dict[int, Behavior] | None = None,
        multi: dict[int, Behavior] | None = None,
        aggregate: list[int] | None = None,
        multi_aggregate: list[int] | None = None,
        mixed_aggregate: list[int] | None = None,
        create_script: list[int] | None = None,
        gen_script: list[int] | None = None,
        no_create_object: bool = False,
        alt: dict[int, Behavior] | None = None,
    ) -> None:
        self._behaviors = dict(behaviors or {})
        self._claim = claim
        self._mixed = mixed
        self._multi = multi
        self._aggregate = list(aggregate or [])
        self._multi_aggregate = list(multi_aggregate or [])
        self._mixed_aggregate = list(mixed_aggregate or [])
        self._create_script = list(create_script or [])
        self._gen_script = list(gen_script or [])
        self._no_create_object = no_create_object
        self._alt = dict(alt) if alt is not None else None
        self._next_handle = 100
        self.captured: dict[int, bytes] = {}
        self.per_handle: dict[int, dict[int, bytes]] = {}
        self.get_attribute_calls = 0
        self.create_calls = 0
        self._varying_calls: dict[int, int] = {}
        self._creation_ordinal: dict[int, int] = {}
        self._creations = 0

    def _issue(self) -> int:
        handle = self._next_handle
        self._next_handle += 1
        return handle

    def _record_creation(self, *handles: int) -> None:
        """Stamp issued handles with their creation ordinal (0 = matrix key)."""
        for handle in handles:
            self._creation_ordinal[handle] = self._creations
        self._creations += 1

    def _capture(self, tmpl: Any, count: int, handle: int) -> None:
        per_key = self.per_handle.setdefault(handle, {})
        for i in range(count):
            atype = int(tmpl[i].type)
            size = int(tmpl[i].ulValueLen)
            addr = tmpl[i].pValue
            value = bytes(ctypes.string_at(addr, size)) if addr and size else b""
            self.captured[atype] = value
            per_key[atype] = value

    def _secret_for(self, handle: int, attr: int) -> bytes:
        """Return the planted secret for one key, falling back to the last capture."""
        per_key = self.per_handle.get(handle)
        if per_key is not None and attr in per_key:
            return per_key[attr]
        return self.captured[attr]

    def C_CreateObject(self, _sh: int, tmpl: Any, count: int, out: Any) -> int:  # noqa: N802
        if tmpl is None:
            # Capability probe from skip_unless_create_object_supported.
            return self._probe_rv()
        self.create_calls += 1
        rv = self._create_script.pop(0) if self._create_script else _OK
        if rv != _OK:
            return rv
        handle = self._issue()
        self._record_creation(handle)
        self._capture(tmpl, count, handle)
        _fill_handle(out, handle)
        return _OK

    def _probe_rv(self) -> int:
        if self._no_create_object:
            return int(CKR_FUNCTION_NOT_SUPPORTED)
        return int(CKR_TEMPLATE_INCOMPLETE)

    def C_GenerateKey(self, _sh: int, _mech: Any, tmpl: Any, count: int, out: Any) -> int:  # noqa: N802
        rv = self._gen_script.pop(0) if self._gen_script else _OK
        if rv != _OK:
            return rv
        handle = self._issue()
        self._record_creation(handle)
        self._capture(tmpl, count, handle)
        _fill_handle(out, handle)
        return _OK

    def C_GenerateKeyPair(  # noqa: N802
        self,
        _sh: int,
        _mech: Any,
        pub_tmpl: Any,
        pub_count: int,
        priv_tmpl: Any,
        priv_count: int,
        pub_out: Any,
        priv_out: Any,
    ) -> int:
        rv = self._gen_script.pop(0) if self._gen_script else _OK
        if rv != _OK:
            return rv
        pub_handle = self._issue()
        priv_handle = self._issue()
        self._record_creation(pub_handle, priv_handle)
        self._capture(pub_tmpl, pub_count, pub_handle)
        self._capture(priv_tmpl, priv_count, priv_handle)
        _fill_handle(pub_out, pub_handle)
        _fill_handle(priv_out, priv_handle)
        return _OK

    def C_DestroyObject(self, _sh: int, _handle: int) -> int:  # noqa: N802
        return _OK

    def _resolve(self, handle: int, attr: int, row_types: list[int], count: int) -> Behavior:
        if (
            self._alt is not None
            and self._creation_ordinal.get(handle, 0) > 0
            and attr in self._alt
        ):
            return self._alt[attr]
        if count == 2 and int(CKA_LABEL) in row_types and self._mixed is not None:
            if attr in self._mixed:
                return self._mixed[attr]
        if count > 2 and self._multi is not None and attr in self._multi:
            return self._multi[attr]
        if attr in self._behaviors:
            return self._behaviors[attr]
        if attr == int(CKA_SENSITIVE):
            return ("fixed", self._claim)
        if attr in self.captured:
            return "readable"
        return "type_invalid"

    def _plan(
        self,
        handle: int,
        attr: int,
        behavior: Behavior,
        *,
        is_query: bool,
        is_reread: bool,
        cap: int,
    ) -> tuple[int, int | None, bytes | None]:
        """Return (rv, ulValueLen, fill) for one row.

        ``fill=None`` leaves pValue alone; ``length=None`` leaves ulValueLen
        unassigned (an untouched output length). ``is_reread`` marks the
        production verification reread, whose buffer opens with 0x5A.
        """
        tag = behavior[0] if isinstance(behavior, tuple) else behavior
        if tag == "generated":
            assert isinstance(behavior, tuple)
            data = b"\x47" * int(behavior[1])
            return _OK, len(data), data
        if tag == "reread":
            assert isinstance(behavior, tuple)
            data = b"\x47" * 32
            if is_reread:
                return int(behavior[1]), len(data), data
            if is_query:
                return _OK, len(data), None
            return _OK, len(data), data
        if tag == "fixed":
            assert isinstance(behavior, tuple)
            data = bytes(behavior[1])
            return _OK, len(data), data
        if tag == "refuse":
            assert isinstance(behavior, tuple)
            return int(behavior[1]), _U64, None
        if tag == "query_only":
            assert isinstance(behavior, tuple)
            if is_query:
                return int(behavior[1]), int(behavior[2]), None
            return _SENSITIVE, _U64, None
        if tag == "untouched":
            assert isinstance(behavior, tuple)
            return int(behavior[1]), None, None
        if tag == "refuse32":
            assert isinstance(behavior, tuple)
            return int(behavior[1]), _U32, None
        if tag == "len_only":
            assert isinstance(behavior, tuple)
            return _OK, int(behavior[1]), None
        if tag == "overlong":
            assert isinstance(behavior, tuple)
            data = self._secret_for(handle, attr)
            if is_query:
                return _OK, len(data), None
            return _OK, int(behavior[1]), data
        if tag == "varying":
            calls = self._varying_calls.get(attr, 0)
            self._varying_calls[attr] = calls + 1
            data = bytes([0x47 + (calls % 2)]) * 32
            return _OK, len(data), data
        if tag == "planted_const":
            assert isinstance(behavior, tuple)
            if is_query:
                return _SENSITIVE, _U64, None
            const_fill = bytearray(b"\x5a" * 16)
            const_fill[int(behavior[2])] = int(behavior[1])
            return _SENSITIVE, _U64, bytes(const_fill)
        if tag == "partial":
            assert isinstance(behavior, tuple)
            if is_query:
                return _SENSITIVE, _U64, None
            secret = self._secret_for(handle, attr)
            head = secret[: int(behavior[1])]
            fill = head + bytes([ts._MATRIX_SENTINEL_BYTE]) * max(cap - len(head), 0)
            return _SENSITIVE, _U64, fill
        if tag == "slice":
            assert isinstance(behavior, tuple)
            if is_query:
                return _SENSITIVE, _U64, None
            secret = self._secret_for(handle, attr)
            off, ln = int(behavior[1]), int(behavior[2])
            frag = secret[off : off + ln]
            buf = bytearray([ts._MATRIX_SENTINEL_BYTE]) * cap
            buf[off : off + len(frag)] = frag
            return _SENSITIVE, _U64, bytes(buf)
        if tag == "const_fill":
            assert isinstance(behavior, tuple)
            if is_query:
                return int(behavior[1]), _U64, None
            return int(behavior[1]), _U64, bytes([int(behavior[2])]) * int(behavior[3])
        if tag == "const_rv":
            assert isinstance(behavior, tuple)
            if is_query:
                return int(behavior[1]), _U64, None
            const_fill = bytearray(b"\x5a" * 16)
            const_fill[int(behavior[3])] = int(behavior[2])
            return int(behavior[1]), _U64, bytes(const_fill)
        if tag == "query_fail_data_ok":
            assert isinstance(behavior, tuple)
            if is_query:
                return int(behavior[1]), _U64, None
            data = self._secret_for(handle, attr)
            return _OK, len(data), data
        if tag == "data_fail":
            assert isinstance(behavior, tuple)
            if is_query:
                return _SENSITIVE, _U64, None
            return int(behavior[1]), None, None
        if tag == "slice_fill":
            assert isinstance(behavior, tuple)
            if is_query:
                return _SENSITIVE, _U64, None
            secret = self._secret_for(handle, attr)
            off, ln, byte = int(behavior[1]), int(behavior[2]), int(behavior[3])
            frag = secret[off : off + ln]
            buf = bytearray([byte]) * cap
            buf[off : off + len(frag)] = frag
            return _SENSITIVE, _U64, bytes(buf)
        if tag == "reread_len":
            assert isinstance(behavior, tuple)
            first_len, reread_rv = int(behavior[1]), int(behavior[2])
            data = b"\x47" * 32
            if is_reread:
                return reread_rv, len(data), data
            if is_query:
                return _OK, len(data), None
            return _OK, first_len, data
        if tag == "query_ok_const":
            assert isinstance(behavior, tuple)
            if is_query:
                data = self._secret_for(handle, attr)
                return _OK, len(data), None
            return int(behavior[1]), _U64, bytes([int(behavior[2])]) * int(behavior[3])
        if tag == "query_ok_data_fail":
            assert isinstance(behavior, tuple)
            if is_query:
                data = self._secret_for(handle, attr)
                return _OK, len(data), None
            return int(behavior[1]), None, None
        if tag == "implausible":
            return _OK, 100000, None
        if tag == "readable":
            data = self._secret_for(handle, attr)
            return _OK, len(data), data
        if tag == "wrong":
            data = b"WRONG-BYTES-FOR-THIS-ATTR-00"
            return _OK, len(data), data
        if tag == "sensitive32":
            return _SENSITIVE, _U32, None
        if tag == "type_invalid":
            return _TYPE_INVALID, _U64, None
        if tag == "ok_sentinel":
            return _OK, _U64, None
        if tag == "unknown":
            return _UNKNOWN_RV, _U64, None
        if tag == "zero":
            return _SENSITIVE, _U64, b"\x00" * cap
        if tag == "scribble":
            return _SENSITIVE, _U64, b"\x5a" * 16
        if tag == "leak":
            data = self._secret_for(handle, attr)
            if is_query:
                return _SENSITIVE, _U64, None
            return _SENSITIVE, len(data), data
        if tag == "bad_length":
            data = self._secret_for(handle, attr)
            if is_query:
                return _SENSITIVE, _U64, None
            return _SENSITIVE, len(data), None
        if tag == "bad_length_q":
            data = self._secret_for(handle, attr)
            if is_query:
                return _SENSITIVE, len(data), None
            return _SENSITIVE, _U64, None
        assert tag == "sensitive", behavior
        return _SENSITIVE, _U64, None

    def C_GetAttributeValue(self, _sh: int, handle: int, tmpl: Any, count: int) -> int:  # noqa: N802
        self.get_attribute_calls += 1
        row_types = [int(tmpl[i].type) for i in range(count)]
        row_rvs: list[int] = []
        for i in range(count):
            attr = row_types[i]
            cap = int(tmpl[i].ulValueLen)
            addr = tmpl[i].pValue
            is_query = not addr
            is_reread = not is_query and cap > 0 and bytes(ctypes.string_at(addr, 1)) == b"\x5a"
            rv, length, fill = self._plan(
                int(handle),
                attr,
                self._resolve(int(handle), attr, row_types, count),
                is_query=is_query,
                is_reread=is_reread,
                cap=cap,
            )
            if fill is not None and addr and not is_query:
                ctypes.memmove(addr, fill, min(len(fill), cap))
            if length is not None:
                tmpl[i].ulValueLen = length
            row_rvs.append(rv)
        if self._aggregate:
            return self._aggregate.pop(0)
        # A multi-member aggregate read has no label row and never carries seal
        # flags (unlike the two-flag seal-claim read); two-member ML-KEM/ML-DSA
        # aggregates count too.
        multi_row = (
            count >= 2
            and int(CKA_LABEL) not in row_types
            and int(CKA_SENSITIVE) not in row_types
            and int(CKA_EXTRACTABLE) not in row_types
        )
        if multi_row and self._multi_aggregate:
            return self._multi_aggregate.pop(0)
        if count == 2 and int(CKA_LABEL) in row_types and self._mixed_aggregate:
            return self._mixed_aggregate.pop(0)
        if _SENSITIVE in row_rvs:
            return _SENSITIVE
        if _TYPE_INVALID in row_rvs:
            return _TYPE_INVALID
        if all(rv == _OK for rv in row_rvs):
            return _OK
        return row_rvs[0]


