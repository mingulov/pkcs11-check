"""QC1 protected-component read-matrix contracts (#54.1).

Behavioral contracts for the table-defined protected read matrix in
``pkcs11_check.testcases.test_sensitivity``: every production leg is driven
through its real test method against a scriptable fake token at the raw
``C_*`` layer. Fakes only; no provider is loaded and no Docker is used.

Covered production behavior:

- ``TestProtectedComponentMatrix.test_sealed_components_unavailable``
  (family x creation x {sensitive-only, both}): per-member raw size-query
  plus data-read, multi-member aggregate, mixed protected/public template,
  and family public controls. Every protected member must be unavailable
  (``CK_UNAVAILABLE_INFORMATION``, both 64- and 32-bit spellings); output
  buffers must stay sentinel-intact on refusal.
- ``TestProtectedComponentMatrix.test_unsealed_components_readable``
  (family x creation x {unsealed, extractable-only}): positive control
  proving the read path works (exact bytes on import paths, non-empty on
  generated paths) plus the extractable-only observation leg.
- Seeded defects: partial leaks, bad lengths (available length on a refused
  member, on either call), aggregate-error-with-leaked-member, nonzero
  scribble (fail); zeroed buffers (visible xfail, never a silent pass).
- Table shape: RSA six-component set with ``CKA_PUBLIC_EXPONENT`` staying
  public, EC/Edwards/Montgomery/DH/X9.42 ``CKA_VALUE``, ML-DSA/ML-KEM seed
  plus value drawn from the tree's own attribute tables, SLH-DSA value
  only with no invented ``CKA_SEED`` row, and the optional-vs-mandatory
  split.
"""

